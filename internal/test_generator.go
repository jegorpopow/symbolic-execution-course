package internal

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"strings"

	"symbolic-execution-course/internal/symbolic"

	"github.com/ebukreev/go-z3/z3"
)

type testParam struct {
	name string
	kind symbolic.ExpressionType
}

type testFunc struct {
	name       string
	params     []testParam
	numResults int
}

type testCase struct {
	name string
	call string
}

func GenerateTestFile(sourceFile string) string {
	source, err := os.ReadFile(sourceFile)
	if err != nil {
		panic(fmt.Sprintf("read source: %v", err))
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, sourceFile, source, parser.ParseComments)
	if err != nil {
		panic(fmt.Sprintf("parse source: %v", err))
	}

	var funcs []testFunc
	for _, decl := range file.Decls {
		fd, ok := decl.(*ast.FuncDecl)
		if !ok || fd.Recv != nil {
			continue
		}
		if fd.Name.Name == "main" || fd.Name.Name == "init" {
			continue
		}
		funcs = append(funcs, testFunc{
			name:       fd.Name.Name,
			params:     extractParams(fd.Type.Params),
			numResults: countResults(fd.Type.Results),
		})
	}

	var body strings.Builder
	anyTests := false
	for _, fn := range funcs {
		fmt.Printf("Generating Test Cases for %s\n", fn.name)
		for _, tc := range generateTestCases(fn, string(source)) {
			fmt.Fprintf(&body, "func %s(t *testing.T) {\n", tc.name)
			fmt.Fprintf(&body, "\tdefer func() {\n")
			fmt.Fprintf(&body, "\t\tif r := recover(); r != nil {\n")
			fmt.Fprintf(&body, "\t\t\tt.Logf(\"panic: %%v\", r)\n")
			fmt.Fprintf(&body, "\t\t}\n")
			fmt.Fprintf(&body, "\t}()\n")
			fmt.Fprintf(&body, "\t%s\n", tc.call)
			fmt.Fprintf(&body, "}\n\n")
			anyTests = true
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by test_generator. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", file.Name.Name)
	fmt.Fprintf(&out, "import \"testing\"\n\n")
	if anyTests {
		out.WriteString(body.String())
	} else {
		fmt.Fprintf(&out, "func TestNothing(t *testing.T) {}\n")
	}

	testPath := strings.TrimSuffix(sourceFile, ".go") + "_test.go"
	if err := os.WriteFile(testPath, []byte(out.String()), 0o644); err != nil {
		panic(fmt.Sprintf("write test file: %v", err))
	}
	return testPath
}

func extractParams(params *ast.FieldList) []testParam {
	if params == nil {
		return nil
	}
	var out []testParam
	for _, field := range params.List {
		kind := paramKind(field.Type)
		for _, name := range field.Names {
			out = append(out, testParam{name: name.Name, kind: kind})
		}
	}
	return out
}

func paramKind(expr ast.Expr) symbolic.ExpressionType {
	if ident, ok := expr.(*ast.Ident); ok {
		switch ident.Name {
		case "bool":
			return symbolic.BoolType
		case "float64", "float32":
			return symbolic.FloatType
		}
	}
	return symbolic.IntType
}

func countResults(results *ast.FieldList) int {
	if results == nil {
		return 0
	}
	n := 0
	for _, field := range results.List {
		if len(field.Names) == 0 {
			n++
		} else {
			n += len(field.Names)
		}
	}
	return n
}

func generateTestCases(fn testFunc, source string) (out []testCase) {
	defer func() {
		if r := recover(); r != nil {
			out = nil
		}
	}()

	results := Analyse(source, fn.name)
	idx := 0
	for _, state := range results {
		if !state.Terminal {
			continue
		}
		if state.Status != TerminalReturn {
			continue
		}
		args, ok := safeExtractArgs(state, fn.params)
		if !ok {
			continue
		}
		out = append(out, testCase{
			name: fmt.Sprintf("Test_%s_path%d", fn.name, idx),
			call: buildCall(fn.name, args, fn.numResults),
		})
		idx++
	}
	return
}

func safeExtractArgs(state Interpreter, params []testParam) (args []string, ok bool) {
	defer func() {
		if r := recover(); r != nil {
			ok = false
		}
	}()
	return extractArgs(state, params)
}

func extractArgs(state Interpreter, params []testParam) ([]string, bool) {
	tr := state.Analyser.Z3Translator
	ctx := tr.GetContext().(*z3.Context)

	translated, err := tr.TranslateExpression(state.PathCondition)
	if err != nil {
		return nil, false
	}
	cond, ok := translated.(z3.Bool)
	if !ok {
		return nil, false
	}

	solver := z3.NewSolver(ctx)
	solver.Assert(cond)
	sat, err := solver.Check()
	if err != nil || !sat {
		return nil, false
	}
	model := solver.Model()
	if model == nil {
		return nil, false
	}

	args := make([]string, 0, len(params))
	for _, p := range params {
		switch p.kind {
		case symbolic.BoolType:
			v := model.Eval(ctx.BoolConst(p.name), true)
			args = append(args, v.String())
		default:
			v := model.Eval(ctx.IntConst(p.name), true)
			args = append(args, parseIntLiteral(v.String()))
		}
	}
	return args, true
}

func parseIntLiteral(s string) string {
	s = strings.TrimSpace(s)
	if strings.HasPrefix(s, "(- ") && strings.HasSuffix(s, ")") {
		return "-" + strings.TrimSpace(s[3:len(s)-1])
	}
	return s
}

func buildCall(name string, args []string, numResults int) string {
	call := fmt.Sprintf("%s(%s)", name, strings.Join(args, ", "))
	switch numResults {
	case 0:
		return call
	case 1:
		return "_ = " + call
	default:
		blanks := make([]string, numResults)
		for i := range blanks {
			blanks[i] = "_"
		}
		return strings.Join(blanks, ", ") + " = " + call
	}
}
